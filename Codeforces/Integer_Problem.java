package Codeforces;
import java.util.Scanner;

public class Integer_Problem {
    public static void main(String[] args){
        Scanner sc = new Scanner(System.in);
        int x = sc.nextInt();
        while(x-- >0){
            int t = sc.nextInt();
            System.out.println(t);
        }
        sc.close();
    }
}
